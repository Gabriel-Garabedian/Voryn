const slug = value => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '')

const makeExercises = (muscle, equipment, type, names, secondaryMuscles = [], difficulty = 'intermediario') =>
  names.map(name => ({
    id: `catalog-${slug(muscle)}-${slug(equipment)}-${slug(name)}`,
    name,
    muscle,
    secondaryMuscles,
    equipment,
    type,
    difficulty,
    media: [],
  }))

